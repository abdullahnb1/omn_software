#!/usr/bin/env python3
"""Exports robot kinematics, physical dimensions, limits, and serial structs to C/C++ headers."""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# Add src and project root to sys.path if not installed
root_dir = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root_dir / "src"))
sys.path.insert(0, str(root_dir))

from mecanum_sim.config import load_config, list_available_robots


def generate_c_header(robot_key: str, output_dir: Path) -> Path:
    """Generates a self-contained firmware header for the specified robot."""
    cfg = load_config(robot=robot_key)
    r = cfg.robot
    R = r.wheel_radius
    lx = r.lx
    ly = r.ly
    L = r.characteristic_length
    w_max = r.actuator.max_speed
    tau_max = r.actuator.max_torque
    vx_max = r.limits.max_vx
    vy_max = r.limits.max_vy
    wz_max = r.limits.max_wz

    # Compute J_inv (4x3) and J_fwd (3x4)
    # J_inv = (1/R) * [[1, -1, -L], [1, 1, L], [1, 1, -L], [1, -1, L]]
    # J_fwd = (R/4) * [[1, 1, 1, 1], [-1, 1, 1, -1], [-1/L, 1/L, -1/L, 1/L]]
    inv_R = 1.0 / R
    j_inv = [
        [inv_R, -inv_R, -inv_R * L],
        [inv_R,  inv_R,  inv_R * L],
        [inv_R,  inv_R, -inv_R * L],
        [inv_R, -inv_R,  inv_R * L],
    ]

    scale_fwd = R / 4.0
    j_fwd = [
        [scale_fwd, scale_fwd, scale_fwd, scale_fwd],
        [-scale_fwd, scale_fwd, scale_fwd, -scale_fwd],
        [-scale_fwd / L, scale_fwd / L, -scale_fwd / L, scale_fwd / L],
    ]

    header_guard = f"{r.name.upper()}_CONFIG_H"
    content = f"""/**
 * ============================================================================
 * @file    {r.name}_config.h
 * @brief   Autogenerated hardware & kinematic firmware configuration.
 *          Target: STM32 / ESP32 / Embedded MCU.
 *          Robot Profile: {r.name}
 * ============================================================================
 */

#ifndef {header_guard}
#define {header_guard}

#ifdef __cplusplus
extern "C" {{
#endif

#include <stdint.h>

/* --- Mechanical & Kinematic Dimensions --- */
#define {r.name.upper()}_WHEEL_RADIUS_M        ({R:.6f}f)
#define {r.name.upper()}_OFFSET_LX_M           ({lx:.6f}f)
#define {r.name.upper()}_OFFSET_LY_M           ({ly:.6f}f)
#define {r.name.upper()}_CHAR_LENGTH_L_M       ({L:.6f}f)
#define {r.name.upper()}_UNLADEN_MASS_KG       ({r.unladen_mass:.3f}f)

/* --- Actuator & Operational Dynamic Limits --- */
#define {r.name.upper()}_MAX_WHEEL_RAD_S       ({w_max:.3f}f)
#define {r.name.upper()}_MAX_MOTOR_TORQUE_NM   ({tau_max:.3f}f)
#define {r.name.upper()}_MAX_VX_M_S            ({vx_max:.3f}f)
#define {r.name.upper()}_MAX_VY_M_S            ({vy_max:.3f}f)
#define {r.name.upper()}_MAX_WZ_RAD_S          ({wz_max:.3f}f)

/* --- Kinematic Transformation Matrices (Row-Major) --- */

/**
 * Inverse Kinematics Matrix (4x3): [w_fl, w_fr, w_rl, w_rr]^T = J_inv * [vx, vy, wz]^T
 */
static const float {r.name.upper()}_J_INV_MATRIX[4][3] = {{
    {{{j_inv[0][0]:.6f}f, {j_inv[0][1]:.6f}f, {j_inv[0][2]:.6f}f}},
    {{{j_inv[1][0]:.6f}f, {j_inv[1][1]:.6f}f, {j_inv[1][2]:.6f}f}},
    {{{j_inv[2][0]:.6f}f, {j_inv[2][1]:.6f}f, {j_inv[2][2]:.6f}f}},
    {{{j_inv[3][0]:.6f}f, {j_inv[3][1]:.6f}f, {j_inv[3][2]:.6f}f}}
}};

/**
 * Forward Kinematics Matrix (3x4): [vx, vy, wz]^T = J_fwd * [w_fl, w_fr, w_rl, w_rr]^T
 */
static const float {r.name.upper()}_J_FWD_MATRIX[3][4] = {{
    {{{j_fwd[0][0]:.6f}f, {j_fwd[0][1]:.6f}f, {j_fwd[0][2]:.6f}f, {j_fwd[0][3]:.6f}f}},
    {{{j_fwd[1][0]:.6f}f, {j_fwd[1][1]:.6f}f, {j_fwd[1][2]:.6f}f, {j_fwd[1][3]:.6f}f}},
    {{{j_fwd[2][0]:.6f}f, {j_fwd[2][1]:.6f}f, {j_fwd[2][2]:.6f}f, {j_fwd[2][3]:.6f}f}}
}};

/* --- Binary Serial Frame Protocol (20 Bytes) --- */
#define SERIAL_VELOCITY_FRAME_HEADER   (0xAA55U)

#pragma pack(push, 1)
typedef struct {{
    uint16_t header;         /**< 0xAA55 magic header */
    float    w_fl;           /**< Front-Left target speed (rad/s) */
    float    w_fr;           /**< Front-Right target speed (rad/s) */
    float    w_rl;           /**< Rear-Left target speed (rad/s) */
    float    w_rr;           /**< Rear-Right target speed (rad/s) */
    uint16_t crc16;          /**< CRC-16/CCITT-FALSE checksum */
}} SerialVelocityFrame_t;
#pragma pack(pop)

#ifdef __cplusplus
}}
#endif

#endif /* {header_guard} */
"""
    output_dir.mkdir(parents=True, exist_ok=True)
    out_path = output_dir / f"{r.name}_config.h"
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Generated MCU header: {out_path}")
    return out_path


def main() -> None:
    parser = argparse.ArgumentParser(description="Export MCU C/C++ firmware headers for mecanum robots.")
    parser.add_argument(
        "--robot",
        default="1",
        help="Robot identifier ('1', '2', '3', 'all', or name). Default: '1'.",
    )
    parser.add_argument(
        "--output-dir",
        default="results",
        help="Destination directory for .h files. Default: 'results'.",
    )
    args = parser.parse_args()

    out_dir = Path(args.output_dir)
    target = str(args.robot).lower()

    if target == "all":
        robots = ["1", "2", "3"]
    else:
        robots = [target]

    for r_key in robots:
        generate_c_header(r_key, out_dir)


if __name__ == "__main__":
    main()

